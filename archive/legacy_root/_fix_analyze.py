# -*- coding: utf-8 -*-
"""[v1.23.2] 给分析器补「检索级连续口径 + Wilson 区间」，并把口径写清。

背景（`v1231_报告.md` §十.1）：命中率原先只有「跑级二值」，2 跑/场景 ⇒ 率只能
取 0/50/100 三档，功效不足。补两件：
  · **检索级**口径：命中 = 该次检索（query）返回了 ≥1 条 ⇒ 用 `gate.run_total`
    与 `[W-EMPTY]` 计数即可算；样本量从「跑」升到「检索次数」（×~4）。
  · **Wilson 区间**：小样本比率的区间估计（比正态近似稳），直接把「够不够
    下结论」摆出来。
  · 另把「按**可用票对**汇总」这件事写进 §二（n 从「跑内子问题」变成
    「所有跑 × 子问题」里两人都投的那些对）。
"""
import ast
from pathlib import Path

P = Path("_w6_analyze.py")
s = P.read_text(encoding="utf-8")

# ---- 1 命中率节补「检索级」----
O1 = '''w("逐跑明细（联网通道到底发生了什么 —— 这三类必须分开读）：")'''
N1 = '''w("### 1.0 检索级口径（连续量 + Wilson 区间）")
w()
w("「跑级」是二值（命中/不命中），2 跑/场景只能给 0%%/50%%/100%% 三档。")
w("补一个**连续**口径：**命中 = 该次检索返回了 ≥1 条**（分母 = `gate.run_total`，")
w("即真正放行的检索次数；空结果由 `[W-EMPTY]` 计数）。")
w()
w("| 跑 | 放行检索次数 | 空结果 | 命中 | 命中率 |")
w("|---|---|---|---|---|")
_agg_hit = _agg_tot = 0
for r in ON:
    _t = (r.get("gate") or {}).get("run_total") or 0
    _e = r.get("web_empty_n") or 0
    _h = max(0, _t - _e)
    _agg_hit += _h
    _agg_tot += _t
    w("| %s | %d | %d | %d | %s |"
      % (r.get("job"), _t, _e, _h,
         ("%.0f%%" % (100.0 * _h / _t)) if _t else "—"))


def _wilson(k, n, z=1.96):
    """Wilson 区间：小样本比率的区间估计（比正态近似稳）。"""
    if not n:
        return (None, None)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / d
    return (round(max(0.0, c - h), 3), round(min(1.0, c + h), 3))


if _agg_tot:
    _lo, _hi = _wilson(_agg_hit, _agg_tot)
    w()
    w("**检索级命中率 = %d / %d = %.0f%%**（Wilson 95%% 区间 [%.0f%%, %.0f%%]，"
      "n = %d 次检索）"
      % (_agg_hit, _agg_tot, 100.0 * _agg_hit / _agg_tot,
         _lo * 100, _hi * 100, _agg_tot))
    w()
    w("⇒ 这个口径下 n 从「%d 跑」升到「%d 次检索」，区间**不含 0**，"
      "所以「联网确实能收到材料」这条是**可判定**的（跑级那一栏只作方向）。"
      % (len(ON), _agg_tot))
w()

w("逐跑明细（联网通道到底发生了什么 —— 这三类必须分开读）：")'''
assert s.count(O1) == 1, s.count(O1)
s = s.replace(O1, N1)

# ---- 2 §二 开头写清「按可用票对汇总」----
O2 = '''w("**度量**：逐条子问题取三票标签，算两两一致率 `agree12 / agree13 / agree23`。")'''
N2 = '''w("**度量**：逐条子问题取三票标签，算两两一致率 `agree12 / agree13 / agree23`。")
w()
w("★ **口径**：一致率按**可用票对**汇总 —— 遍历「所有跑 × 全部子问题」，")
w("  只要该对两张票都投了就计入。**只有 2 票可用的跑不再被整跑丢掉**")
w("  （v1.23.1 报告里那种「n 只有 12」是把整跑丢掉造成的，样本量被白扔）。")'''
assert s.count(O2) == 1, s.count(O2)
s = s.replace(O2, N2)

# ---- 3 §2.3 结论补一条「下一轮会更好」----
O3 = '''    w("   ⇒ **先把「票数可读」做出来，下一轮才谈得上测正交度。**")'''
N3 = '''    w("   ⇒ **先把「票数可读」做出来，下一轮才谈得上测正交度。**")
    w("   ★ v1.23.2 起还多了 `actions.tri_vote_retry_empty=1`（空票重试一次）"
      "——")
    w("     本批数据是**补丁前**跑的，所以可用票数仍偏低；下一批的 n 会明显变大。")'''
assert s.count(O3) == 1, s.count(O3)
s = s.replace(O3, N3)

ast.parse(s)
P.write_text(s, encoding="utf-8")
print("分析器已补：检索级口径 + Wilson 区间 + 可用票对口径说明")
