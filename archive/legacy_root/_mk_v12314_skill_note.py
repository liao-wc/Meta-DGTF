import re
from pathlib import Path

p = Path.home() / ".workbuddy" / "skills" / "dgtf-version-bump" / "SKILL.md"
raw = p.read_bytes()
crlf = raw.count(b"\r\n") > (raw.count(b"\n") - raw.count(b"\r\n"))
s = raw.decode("utf-8").replace("\r\n", "\n")

SENT = "### 27. \u2605\u2605 \u89e3\u6790\u5386\u53f2\u4ea7\u7269\u524d"

ADD = """
### 27. ★★ 解析历史产物前**先量覆盖率**再写正则（半角/全角冒号）

v1.23.14 要把 368 份产物 md 当历史语料，第一版抽取器把键写成全角冒号
（`**资源**：`），实测**命中 0 条**，样本停在 17 —— 我一度以为「语料只有 17 份」。
真相是同一份产物里**两种冒号混用**：`**资源**: N 次 LLM` 是半角、
`**调度**：` 是全角。

**做法**：① 正则一律写 `[:：]`；② **先跑一次覆盖率统计**
（对每个待抽字段数一遍「有几个文件命中」），再决定抽取器对不对。
覆盖率表本身也是产物的一部分（本项目：`_hist_corpus*.py`）。

### 28. ★★ 判据的样例要选在「两种实现会分歧」的地方

v1.23.14 的判据首版在 **M5 / M6 两个变异体上假绿**：

- **M5（样本门槛）**：我用 0/1 层测「实际停圈只有 1 份样本时不该采纳」——
  但 0/1 层的 `_layer_floor` 是 4 ⇒「采纳（1+1=2）」与「不采纳（上限 4）」
  **都被钳到 4**，判据根本分辨不出。改用**元层**（floor 5）才判红。
- **M6（相对 vs 绝对阈值）**：我的合成样例里「绝对阈值 40 万」与
  「相对判据（≥ 全语料 p75）」结论**恰好一致**。
  补一条**两者会分歧**的样例（同类中位 90 万 < 全语料 p75 500 万、
  但 > 绝对阈值 40 万）才判红。

**通则**：写判据时先问「我这条样例，在**错误实现**下会不会给出**相同**结论？」
会 ⇒ 这条样例没有判别力，要换一个两种实现分岔的输入。

### 29. ★★ 读快照字段前先 `grep` 真实字段名（`rounds` vs `rounds_run`）

v1.23.13 的 `_auto_history` 把「实际停圈」读成 `views.*.rounds`，
真实字段是 **`rounds_run`**（`View` 的 dataclass 字段名）。
`dict.get` 读错**不报错、返回 None** ⇒ 这条读数**一整版都没生效**，
而产物里也没有任何渲染点写它 ⇒ 「信号既没被读、也没被记」，静默到底。

**做法**：读快照/产物字段前，先在源码里 `grep` 该字段的**定义与赋值点**
（本项目第 N 次踩同类：§「留痕字段/属性名，用之前先 grep」）。
★ 另一条配套：**凡是模型/引擎算出来但没人读的信号，都要有一个渲染点**，
否则它永远只是内存里的一个数。

### 30. ★ 读数对**取样窗口**敏感 ⇒ 阈值写「相对判据」，并把 n 一起报出来

v1.23.14 实测：同一批语料，只把「取最近多少份」从 368 改成 200，
`tokens` p75 就从 **1,050,814 变成 711,161（差 1.5 倍）**、
种子上限 p50 从 4/4 变成 3/3。

⇒ ① **别写绝对阈值**（「40 万 token 就算贵」会随窗口漂移失效），
写**相对判据**（同类题中位 vs 全语料 p75）；
② 产物里的读数行**必须同时报样本量、来源、每个读数的 n**，
让读的人自己判断可信度（`n=1` 的一致率与 `n=192` 的上限不是一个量级）。

### 31. ★ 单条样本的「中位数」不是可用读数 —— 聚合带 n，策略按 n 决定信不信

v1.23.14 引入 `_AUTO_ACT_MIN = 3`：实际停圈不满 3 份样本就不采纳，
退回「种子上限」。**没这条门槛时**，1 份样本的 `{'1': 1}` 会盖掉
200 份的种子上限分布。

**通则**：任何聚合读数都要带上 `n`；**消费方要显式决定「n 到多少才信」**，
而不是「有值就用」。并且样本数要**总是记**（哪怕中位数没被采纳）——
否则读的人分不清「没有样本」与「有样本但没采纳」。
"""

if SENT in s:
    print("[skip] 已追加过")
else:
    if not s.endswith("\n"):
        s += "\n"
    s += ADD
    out = s.replace("\n", "\r\n").encode("utf-8") if crlf else s.encode("utf-8")
    p.write_bytes(out)
    print("已追加第 27-31 条")

chk = p.read_bytes()
fixed = re.sub(rb"\r+\n", b"\r\n", chk)
if fixed != chk:
    p.write_bytes(fixed)
    chk = fixed
    print("★ 修复了 CRCRLF")
print("技能 CRLF %d | CRCRLF %d | 字节 %d"
      % (chk.count(b"\r\n"), chk.count(b"\r\r\n"), len(chk)))
