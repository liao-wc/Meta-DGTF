w("## 十二、经验教训")
w()
w("1. ★ **「不可判定」往往是口径错，不是样本少**。观测式的「组间 ≥ 组内」里，")
w("   组内变异混进了**上游机制的变异**（子问题每跑重拆）—— 这种口径")
w("   **结构性不可判定**，跑一万次也一样。正解是**受控实验**：固定刺激、")
w("   只让被测机制重投。")
w("2. ★ **换口径前先问「这个指标在结构上能不能变」**。本版第一版写的")
w("   「第三票改变多数结论」在 3 票制下**恒为 0**（两人一致时第三人")
w("   永远改不了多数）—— 与「只升不降的指标是自欺」同族。")
w("3. ★ **变异体必须打在判据读的那个东西上**（本项目第 N 次）：温度 0.7 臂")
w("   作为负对照，用来证明 ICC 有判别力。")
w("4. ★ **判据的锚不能写死会变的东西**：`check_v1232_audit` 把被测文件写成")
w("   `元DGTF-V1.23.2.py` ⇒ 升版后「smoke SRC 指向本版」必判红。")
w("   改为取**已加载模块的 `__file__`**。")
w("5. ★ **一类判据 > 一处修复**：id 归一化做成审计 L 类后，**当场又扫出两处**")
w("   （子问题 id、`voter` 位置）—— 只修「看到的那一处」会漏掉同族。")
w("6. ★ **注入器一次只改自己那一档，但会用别档的锚**：`_mk_v1232_smoke_checks`")
w("   从 `def check_v1232_audit` 换到 MARK ⇒ 排在它前面的修改会被抹掉。")
w("   修别档必须改**那一档的注入器**，不是生成器。")
